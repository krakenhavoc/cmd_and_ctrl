package effects

import "github.com/krakenhavoc/cmd_and_ctrl/server/internal/game"

// Wail of the Nim — Instant {2}{B}:
//
//	"Choose one —
//	 • Regenerate each creature you control.
//	 • Wail of the Nim deals 1 damage to each creature and each player.
//	 Entwine {B} (Choose both if you pay the entwine cost.)"
//
// Entwine is CR 702.42 (#3866). The regeneration is Golgari Charm's: one
// shield on each creature you control as it resolves. The damage is
// Pestilence's, to every creature and then every player, one damage
// instance. Entwined, the shields go up before the damage (CR 702.42b),
// so a creature of yours the 1 damage would kill is regenerated by the
// shield this spell gave it.
//
// No simplification.
func init() {
	Register(Spec{
		OracleID:      "dcf503b5-c7ef-49e5-87ed-3b8758197446",
		Name:          "Wail of the Nim",
		Completeness:  CompletenessFull,
		OptionalCosts: []game.AdditionalCost{Entwine("{B}")},
		Modes: Entwining(ChooseOne(
			ModeDoing("Regenerate each creature you control.", nil,
				func(_ *game.StackItem, ctx *Context, _ int) error {
					return regenerateEachCreatureControlledBy(ctx, ctx.Controller())
				}),
			ModeWithPurpose(ModeDoing("Wail of the Nim deals 1 damage to each creature and each player.", nil,
				func(_ *game.StackItem, ctx *Context, _ int) error {
					return b23DamageEachCreatureAndEachPlayer(ctx, 1)
				}), game.Purpose{Sweep: game.Sweep{Matches: game.SweepCreatures, How: game.SweepDamage, Amount: 1}}),
		)),
	})
}
