// census_test.go is to the card-coverage roadmap what
// snapshot_drift_test.go is to the snapshot encoder: the reason the
// document will still be true in six months.
//
// The roadmap's counts were hand-typed. Nothing checked them, and
// they drifted — once by being DERIVED instead of measured (319 for a
// real 320, which is why the doc carries a "always MEASURE this line"
// warning), once by reporting registry KEYS as if they were cards
// (60 of them are MDFC back faces, so "504 specs" was 444 cards plus
// 60 land backs and the card count was overstated by ~13%).
//
// # Which way does the truth flow
//
// The document is the source of truth this test READS. It is not
// regenerated wholesale, and the test never edits a sentence a person
// wrote. What it owns is one delimited block — everything between
// BeginMarker and EndMarker — which holds only measured numbers and
// nothing else.
//
// That split is the whole design, and it is the lesson from
// internal/legal's TestTimingAgreement: `-update` is a convenience,
// and a convenience that is allowed to rewrite hand-authored claims
// converts the test into a tautology. Here `-update` can only ever
// rewrite numbers that came out of effects.All() in the first place,
// so regenerating cannot launder a wrong claim into a right-looking
// one. The prose around the block — the historical "438 → 504 at
// commit e5fc440" records, the batch table, the narrative — stays
// hand-authored and stays untouched, because it says what was true at
// a named commit and should not be quietly rewritten to today.
//
// # Who is allowed to write it (Discussion #1231)
//
// The block used to be regenerated by whichever card PR noticed it
// was stale, and that is what made it the reliable source of forced
// rebases across the whole card-batch queue: two PRs branched off the
// same develop commit both ran `-update`, both landed a plausible but
// different absolute count, and whichever merged second conflicted on
// exactly these lines even though the two PRs never touched the same
// card. 14 of develop's 20 commits in one week touched only this
// block.
//
// The fix is that a PR no longer regenerates the block at all — only
// CI does, on a push to develop or main, after the push has already
// merged (see the "Census — refresh" and "Census — commit refresh"
// steps in .github/workflows/ci-cd.yml). A PR branch is naturally
// behind whatever landed on develop since it branched; that is
// expected drift CI resolves on the next push, not a defect in the
// PR, so TestRoadmapCensusIsCurrent must not fail a PR for it. The
// CENSUS_ENFORCE environment variable is how the test tells a PR (or
// a developer's own machine) apart from the push job that is allowed
// to demand freshness — see staleCensusActionFor below. `-update`
// keeps working exactly as before for anyone who wants to check or
// refresh the block by hand; it is just no longer something a card PR
// is expected to run.
var update = flag.Bool("update", false,
	"rewrite the generated census block in the card-coverage roadmap")

// staleCensusAction is what TestRoadmapCensusIsCurrent should do once
// it has found the doc's census block does not match the measured
// one. Pulling the decision out into its own function — rather than
// inlining the env/flag checks in the test — means the three-way
// branch can be driven by TestStaleCensusActionFor as a plain table
// test, with no real file and no process environment involved.
type staleCensusAction int

const (
	// staleCensusRewrite splices the measured block into the doc.
	// This is `-update`: the manual escape hatch for a developer
	// checking the doc locally, and also what the CI "Census —
	// refresh" step runs on every push to develop and main, before
	// the test suite sees the tree.
	staleCensusRewrite staleCensusAction = iota

	// staleCensusFail reports the mismatch as a test failure, with
	// the full measured-vs-doc diff. Only the push job's "Server —
	// test" step sets CENSUS_ENFORCE=1, and only after the refresh
	// step above has already run `-update` against the same tree, so
	// a failure here means TakeCensus() and the just-rewritten doc
	// still disagree — the write did not take — not that the doc is
	// a few commits behind.
	staleCensusFail

	// staleCensusSkip is the default: a PR, or a bare local
	// `go test ./...`. The block is expected to be behind whatever
	// merged to develop since the branch point; CI reconciles it on
	// develop, not here, so failing would be exactly the false
	// positive Discussion #1231 was filed over.
	staleCensusSkip
)

// staleCensusActionFor decides the three-way branch above from the
// `-update` flag and the CENSUS_ENFORCE environment variable.
// `-update` always wins — a developer who passed it explicitly wants
// the file rewritten regardless of which job is running. Otherwise
// CENSUS_ENFORCE=="1" (set only by the push job in ci-cd.yml) fails,
// and anything else — unset, empty, "0", or any other value — skips.
func staleCensusActionFor(update bool, censusEnforce string) staleCensusAction {
	switch {
	case update:
		return staleCensusRewrite
	case censusEnforce == "1":
		return staleCensusFail
	default:
		return staleCensusSkip
	}
}

// TestStaleCensusActionFor is the table test the split above exists
// to make cheap: the CI/PR/local three-way branch, driven directly
// with no real file on disk and no process environment touched, so
// it cannot flake and cannot leave CENSUS_ENFORCE set for a later
// test in the same binary.
func TestStaleCensusActionFor(t *testing.T) {
	tests := []struct {
		name          string
		update        bool
		censusEnforce string
		want          staleCensusAction
	}{
		{"update flag wins over enforce unset", true, "", staleCensusRewrite},
		{"update flag wins over enforce=1", true, "1", staleCensusRewrite},
		{"enforce=1 without update fails", false, "1", staleCensusFail},
		{"enforce unset without update skips (PR default)", false, "", staleCensusSkip},
		{"enforce=0 without update still skips", false, "0", staleCensusSkip},
		{"enforce garbage without update still skips", false, "yes", staleCensusSkip},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			if got := staleCensusActionFor(tc.update, tc.censusEnforce); got != tc.want {
				t.Errorf("staleCensusActionFor(%v, %q) = %v, want %v",
					tc.update, tc.censusEnforce, got, tc.want)
			}
		})
	}
}

// TestFaceSuffixMatchesCatalogKey pins this package's copy of the
// face-key convention to the game package's producer of it. The
// census splits cards from back faces by matching "#N" on the
// registry key; if game.CatalogKeyForFace ever spells the key
// differently, the census would quietly report 60 extra "cards"
// rather than failing, which is the exact error this whole file
// exists to prevent.
func TestFaceSuffixMatchesCatalogKey(t *testing.T) {
	const oracle = "3d6fa57a-aa53-4b5c-b8af-a7612c823117"

	if got := game.CatalogKeyForFace(oracle, 0); faceSuffix.MatchString(got) {
		t.Errorf(`faceSuffix matched the FRONT-face key %q.

Face 0 keeps the bare oracle ID — that is what makes the composite
key a no-op for every single-faced card. A pattern that matches it
would count every card in the catalog as a back face.`, got)
	}
	back := game.CatalogKeyForFace(oracle, 1)
	if !faceSuffix.MatchString(back) {
		t.Errorf(`faceSuffix did not match the BACK-face key %q that
game.CatalogKeyForFace produces.

The convention moved and coverage/census.go did not. Update faceSuffix
to the new shape — until you do, TakeCensus reports every MDFC land
back as a whole card and the roadmap overstates coverage.`, back)
	}
}

// TestCensusIsInternallyConsistent is the cheap arithmetic guard: the
// two splits must both add up to the key count. It costs nothing and
// it means a later refactor of TakeCensus cannot drop a bucket
// without saying so.
func TestCensusIsInternallyConsistent(t *testing.T) {
	c := TakeCensus()
	if c.Keys == 0 {
		t.Fatal(`the registry is empty.

TakeCensus measured zero specs, which means this package is not
importing effects for real (a blank import that got dropped, a build
tag) — not that the catalog is empty.`)
	}
	if got := c.WholeCards + c.BackFaces; got != c.Keys {
		t.Errorf("whole cards (%d) + back faces (%d) = %d, want Keys = %d",
			c.WholeCards, c.BackFaces, got, c.Keys)
	}
	if got := c.Full + c.Caveats + c.Unreviewed; got != c.Keys {
		t.Errorf("full (%d) + caveats (%d) + unreviewed (%d) = %d, want Keys = %d",
			c.Full, c.Caveats, c.Unreviewed, got, c.Keys)
	}
}

// TestRoadmapCensusIsCurrent is the drift guard.
//
// Missing markers are always fatal — see the first block below — but
// a *stale* block (markers present, numbers behind) is not: what
// happens next depends on staleCensusActionFor's read of `-update`
// and CENSUS_ENFORCE, because the same mismatch means three different
// things depending on who is running the test:
//
//   - the push job, right after its own "Census — refresh" step
//     (CENSUS_ENFORCE=1): a mismatch here means the refresh did not
//     take, so it fails with the full diff;
//   - a developer running `-update` by hand: rewrite, same as always;
//   - anything else — a PR, a bare local `go test ./...`
//     (CENSUS_ENFORCE unset): skip. The block is refreshed by CI on
//     develop and main (Discussion #1231), so a PR branch trailing
//     develop is expected, not a bug in the PR, and failing it here
//     is the false positive that used to force a rebase on every
//     card PR in flight whenever another one merged first.
func TestRoadmapCensusIsCurrent(t *testing.T) {
	raw, err := os.ReadFile(RoadmapPath)
	if err != nil {
		t.Fatalf("read %s: %v", RoadmapPath, err)
	}
	doc := string(raw)
	want := TakeCensus().Block()

	got, ok := Extract(doc)
	if !ok {
		t.Fatalf(`%s has no generated census block.

The markers are gone, so nothing is checking the roadmap's numbers.
Paste this back into the Progress section, or run:

  go test ./internal/cards/coverage/ -update

%s`, RoadmapPath, want)
	}
	if got == want {
		return
	}

	switch staleCensusActionFor(*update, os.Getenv("CENSUS_ENFORCE")) {

	case staleCensusRewrite:
		next, ok := Splice(doc, want)
		if !ok {
			t.Fatalf("markers vanished between read and splice in %s", RoadmapPath)
		}
		if err := os.WriteFile(RoadmapPath, []byte(next), 0o644); err != nil {
			t.Fatalf("write %s: %v", RoadmapPath, err)
		}
		t.Logf("updated the census block in %s", RoadmapPath)
		return

	case staleCensusSkip:
		t.Skipf(`the census block in %s is behind the live catalog.

That is expected here: CI refreshes this block on every push to
develop and main (Discussion #1231), so a PR branch — or a bare local
"go test ./..." — is not judged against it. This is not something to
fix in a PR; do not run -update to "correct" it, that is exactly the
regeneration that used to collide across every card PR in flight.

Set CENSUS_ENFORCE=1 to enforce freshness here (that is what the push
job does, right after its own refresh step), or run

  go test ./internal/cards/coverage/ -update

to refresh the block by hand.`, RoadmapPath)
		return
	}

	// staleCensusFail: CENSUS_ENFORCE=1 and the block still disagrees
	// with the catalog after CI's own refresh step already ran
	// -update against this same tree — the write did not take.
	c := TakeCensus()
	t.Errorf(`the card-coverage roadmap disagrees with the live catalog.

%s is out of date. The catalog moves under it every time a card PR
merges, and the numbers in that file are read by people deciding what
to work on next.

Measured right now, from len(effects.All()):

  registry keys          %d
  whole cards            %d   <- the number to quote as "cards we automate"
  MDFC back faces        %d   <- half a card each; those cards are still gaps
  declared full          %d
  declared caveats       %d
  declared unreviewed    %d

Fix it mechanically:

  go test ./internal/cards/coverage/ -update

That rewrites ONLY the block between the two HTML comment markers.
Every hand-written sentence in the roadmap — including the historical
"N → M at commit <sha>" records, which are true of their commit and
must not be retconned — is left exactly as it is.

%s`,
		RoadmapPath,
		c.Keys, c.WholeCards, c.BackFaces, c.Full, c.Caveats, c.Unreviewed,
		diff(got, want))
}

// diff renders the two blocks line by line, marking the first line
// that differs. A whole-block dump is unreadable at twelve lines of
// markdown; the reader wants the number that moved.
func diff(got, want string) string {
	g, w := strings.Split(got, "\n"), strings.Split(want, "\n")
	var b strings.Builder
	b.WriteString("Line-by-line (- in the doc, + measured):\n")
	n := len(g)
	if len(w) > n {
		n = len(w)
	}
	for i := 0; i < n; i++ {
		var gl, wl string
		if i < len(g) {
			gl = g[i]
		}
		if i < len(w) {
			wl = w[i]
		}
		if gl == wl {
			continue
		}
		if gl != "" {
			b.WriteString("  - " + gl + "\n")
		}
		if wl != "" {
			b.WriteString("  + " + wl + "\n")
		}
	}
	return b.String()
}
