package main

// generate.go — the files the split writes besides the moved code, and the
// edits outside the effects tree that make the rest of the server link the
// whole catalog.

import (
	"bytes"
	_ "embed"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const generatedMainTest = "main_test.go"

const genHeader = "// Code generated by scripts/split-effects (#5906, ADR 0224). DO NOT EDIT.\n\n"

//go:embed flat_fs.go.txt
var flatFSTemplate string

func writeFile(path string, b []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, b) {
		return nil
	}
	return os.WriteFile(path, b, 0o644)
}

// aggregatorSource is cards/cards.go: it links every shard of the table.
func aggregatorSource(tbl *rangeTable) []byte {
	var b bytes.Buffer
	b.WriteString(genHeader)
	b.WriteString("// Package cards links every card shard of the catalog into a binary. Import it\n")
	b.WriteString("// for its side effect wherever the whole catalog is read: a main package, or\n")
	b.WriteString("// the tests of a package that reaches internal/cards/effects. Its init runs\n")
	b.WriteString("// after every shard has registered, and tells the core the catalog is whole;\n")
	b.WriteString("// effects.Lookup, All and Has panic before that (ADR 0224).\n")
	b.WriteString("package cards\n\nimport (\n")
	fmt.Fprintf(&b, "\t%q\n", effectsPath)
	for _, r := range tbl.cards {
		fmt.Fprintf(&b, "\t_ %q\n", importPath(shardKey(r.id)))
	}
	b.WriteString(")\n\nfunc init() { effects.MarkCatalogComplete() }\n")
	return b.Bytes()
}

// mainTestSource is tests/<id>/main_test.go.
func mainTestSource(id string) []byte {
	var b bytes.Buffer
	b.WriteString(genHeader)
	fmt.Fprintf(&b, "package %s\n\n", pkgName(testKey(id)))
	b.WriteString("import (\n\t\"testing\"\n\n")
	fmt.Fprintf(&b, "\t_ %q // every card: tests look cards up by name\n", effectsPath+"/cards")
	fmt.Fprintf(&b, "\t%q\n)\n\n", importPath(keyTst))
	b.WriteString("// TestMain is the one TestMain of the old package, for every test package.\n")
	b.WriteString("func TestMain(m *testing.M) { effectstest.RunTestMain(m) }\n")
	return b.Bytes()
}

// writeGenerated writes the aggregator, each test package's main_test.go and
// effectstest's flat view of the tree.
func writeGenerated(effDir string, tbl *rangeTable, testIDs []string) error {
	if err := writeFile(filepath.Join(effDir, "cards", "cards.go"), aggregatorSource(tbl)); err != nil {
		return err
	}
	for _, id := range testIDs {
		if err := writeFile(filepath.Join(effDir, "tests", id, generatedMainTest), mainTestSource(id)); err != nil {
			return err
		}
	}
	return writeFile(filepath.Join(effDir, "effectstest", "flat_fs.go"), []byte(genHeader+flatFSTemplate))
}

// replaceOnce edits a file outside the effects tree: old must occur exactly
// once (or new must already be there, which makes the step idempotent).
func replaceOnce(path, old, new string) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	s := string(b)
	if new != "" && strings.Contains(s, new) && !strings.Contains(s, old) {
		return nil
	}
	if n := strings.Count(s, old); n != 1 {
		return fmt.Errorf("%s: expected the text below exactly once, found it %d times; edit the file by hand and re-run:\n%s", path, n, old)
	}
	return os.WriteFile(path, []byte(strings.Replace(s, old, new, 1)), 0o644)
}

// linkCatalog makes every binary and test binary that reaches the effects
// core also link the aggregator: a main package gets catalog_link.go, and
// any other package whose tests reach the core gets
// effects_catalog_link_test.go (an external test file, so it cannot cycle).
func linkCatalog(serverDir string) ([]string, error) {
	out, err := run(serverDir, "go", "list", "-f",
		"{{.ImportPath}}\t{{.Name}}\t{{.Dir}}\t{{join .Deps \" \"}}\t{{join .TestImports \" \"}} {{join .XTestImports \" \"}}", "./...")
	if err != nil {
		return nil, err
	}
	type pkg struct {
		path, name, dir string
		deps            map[string]bool
		testImports     []string
	}
	pkgs := map[string]*pkg{}
	var order []string
	for _, l := range strings.Split(strings.TrimSpace(out), "\n") {
		f := strings.Split(l, "\t")
		if len(f) != 5 {
			return nil, fmt.Errorf("go list: unexpected line %q", l)
		}
		p := &pkg{path: f[0], name: f[1], dir: f[2], deps: map[string]bool{}, testImports: strings.Fields(f[4])}
		for _, d := range strings.Fields(f[3]) {
			p.deps[d] = true
		}
		pkgs[p.path] = p
		order = append(order, p.path)
	}
	sort.Strings(order)
	agg := effectsPath + "/cards"
	var wrote []string
	for _, path := range order {
		p := pkgs[path]
		if path == effectsPath || strings.HasPrefix(path, effectsPath+"/") {
			continue
		}
		if p.name == "main" {
			if !p.deps[effectsPath] {
				continue
			}
			src := genHeader + "package main\n\n" +
				"// The binary reads the card catalog, so it links every card shard (ADR 0224).\n" +
				fmt.Sprintf("import _ %q\n", agg)
			f := filepath.Join(p.dir, "catalog_link.go")
			if err := writeFile(f, []byte(src)); err != nil {
				return nil, err
			}
			wrote = append(wrote, f)
			continue
		}
		reach := p.deps[effectsPath]
		for _, ti := range p.testImports {
			if ti == effectsPath || (pkgs[ti] != nil && pkgs[ti].deps[effectsPath]) {
				reach = true
			}
		}
		if !reach {
			continue
		}
		src := genHeader + "package " + p.name + "_test\n\n" +
			"// These tests reach the card catalog, so the test binary links every card\n" +
			"// shard (ADR 0224): without it effects.Lookup, All and Has panic.\n" +
			fmt.Sprintf("import _ %q\n", agg)
		f := filepath.Join(p.dir, "effects_catalog_link_test.go")
		if err := writeFile(f, []byte(src)); err != nil {
			return nil, err
		}
		wrote = append(wrote, f)
	}
	return wrote, nil
}
